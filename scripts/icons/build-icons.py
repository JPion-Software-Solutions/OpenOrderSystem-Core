#!/usr/bin/env python3
"""
Builds the OOS icon key contract and the Default Pack from icon-map.json.

Usage (from OpenOrderSystem-Core):
    python3 scripts/icons/build-icons.py                       # downloads the pinned lucide-static from the npm registry
    python3 scripts/icons/build-icons.py path/to/lucide/icons  # uses an already extracted icons folder

Outputs:
    wwwroot/icons/default/sprite.svg                            SVG sprite, one <symbol> per distinct Lucide icon
    wwwroot/icons/default/thumbnail.svg                         Preview image for DefaultIconPack.ThumbnailUrl
    wwwroot/icons/default/LICENSE-lucide.txt                    Lucide's ISC license (required with redistribution)
    Services/UI/Theme/Icons/IconKeys.g.cs                       The key contract, as string constants
    Developer Docs/Services/UI/Theme/Icons/icon-keys.html       Self-contained preview of every key

Generated files are overwritten; edit icon-map.json and rerun instead of editing them.

The key map inside Services/UI/Theme/Icons/BuiltinPacks/DefaultIconPack.cs is maintained by hand so the
pack stays a single file. The script checks it against icon-map.json and lists any lines to change.
"""

import base64
import hashlib
import html
import io
import json
import re
import shutil
import sys
import tarfile
import tempfile
import urllib.request
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = SCRIPT_DIR.parent.parent
MAP_FILE = SCRIPT_DIR / "icon-map.json"

ICONS_WWW = PROJECT_ROOT / "wwwroot" / "icons" / "default"
SPRITE_OUT = ICONS_WWW / "sprite.svg"
THUMBNAIL_OUT = ICONS_WWW / "thumbnail.svg"
LICENSE_OUT = ICONS_WWW / "LICENSE-lucide.txt"
ICONS_SRC = PROJECT_ROOT / "Services" / "UI" / "Theme" / "Icons"
KEYS_OUT = ICONS_SRC / "IconKeys.g.cs"
PACK_FILE = ICONS_SRC / "BuiltinPacks" / "DefaultIconPack.cs"
PREVIEW_OUT = PROJECT_ROOT / "Developer Docs" / "Services" / "UI" / "Theme" / "Icons" / "icon-keys.html"

ICONS_NS = "OpenOrderSystem.Core.Services.UI.Theme.Icons"
KEY_PATTERN = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
SVG_BODY = re.compile(r"<svg\b[^>]*>(.*)</svg>", re.S)
MAP_ENTRY = re.compile(r'\["([^"]+)"\]\s*=\s*"([^"]+)"')
MAP_VERSION = re.compile(r'const string Version = "([^"]+)"')
GENERATED_HEADER = [
    "// <auto-generated>",
    "// Generated by scripts/icons/build-icons.py from scripts/icons/icon-map.json. Do not edit.",
    "// </auto-generated>",
    "",
]


def pascal(kebab: str) -> str:
    return "".join(part.capitalize() for part in kebab.split("-"))


def fetch_lucide(version: str, workdir: Path) -> Path:
    """Downloads lucide-static from the npm registry and checks it against the registry's sha512 integrity."""
    print(f"Downloading lucide-static@{version} ...")
    with urllib.request.urlopen(f"https://registry.npmjs.org/lucide-static/{version}") as resp:
        dist = json.load(resp)["dist"]
    with urllib.request.urlopen(dist["tarball"]) as resp:
        data = resp.read()

    algo, _, expected = dist["integrity"].partition("-")
    if algo != "sha512" or base64.b64encode(hashlib.sha512(data).digest()).decode() != expected:
        raise RuntimeError("lucide-static tarball failed its integrity check")

    with tarfile.open(fileobj=io.BytesIO(data)) as tar:
        try:
            tar.extractall(workdir, filter="data")
        except TypeError:  # Python without extraction filters
            tar.extractall(workdir)
    return workdir / "package" / "icons"


def symbol_body(svg_file: Path) -> str:
    text = svg_file.read_text(encoding="utf-8")
    match = SVG_BODY.search(text)
    if not match:
        raise ValueError(f"Could not parse {svg_file.name}")
    lines = [line.strip() for line in match.group(1).strip().splitlines()]
    return "".join(line for line in lines if line)


def main() -> int:
    spec = json.loads(MAP_FILE.read_text(encoding="utf-8"))
    version = spec["lucideVersion"]
    categories = spec["categories"]
    thumbnail_keys = spec.get("thumbnailKeys", [])

    # Validate keys and collect the full key list
    all_keys: list[tuple[str, str, str]] = []  # (category, short key, lucide name)
    errors = []
    for cat, info in categories.items():
        if not KEY_PATTERN.match(cat):
            errors.append(f"Bad category name: {cat}")
        for short, lucide in info["keys"].items():
            if not KEY_PATTERN.match(short):
                errors.append(f"Bad key: {cat}.{short}")
            all_keys.append((cat, short, lucide))

    lucide_for = {f"{cat}.{short}": lucide for cat, short, lucide in all_keys}
    for key in thumbnail_keys:
        if key not in lucide_for:
            errors.append(f"thumbnailKeys: unknown key '{key}'")

    tmp = None
    if len(sys.argv) > 1:
        icons_dir = Path(sys.argv[1])
    else:
        tmp = Path(tempfile.mkdtemp())
        icons_dir = fetch_lucide(version, tmp)

    try:
        for cat, short, lucide in all_keys:
            if not (icons_dir / f"{lucide}.svg").exists():
                errors.append(f"{cat}.{short}: Lucide icon '{lucide}' not found")
        if errors:
            print("\n".join(errors), file=sys.stderr)
            return 1

        # Sprite: one symbol per distinct Lucide icon, so keys sharing a glyph share a symbol
        distinct = sorted({lucide for _, _, lucide in all_keys})
        bodies = {name: symbol_body(icons_dir / f"{name}.svg") for name in distinct}
        symbols = [f'<symbol id="lucide-{name}" viewBox="0 0 24 24">{bodies[name]}</symbol>' for name in distinct]
        ICONS_WWW.mkdir(parents=True, exist_ok=True)
        SPRITE_OUT.write_text(
            f"<!-- OOS Default Pack. Icons from Lucide v{version} (ISC), see LICENSE-lucide.txt. Generated by scripts/icons/build-icons.py -->\n"
            '<svg xmlns="http://www.w3.org/2000/svg"><defs>\n' + "\n".join(symbols) + "\n</defs></svg>\n",
            encoding="utf-8")

        license_src = icons_dir.parent / "LICENSE"
        if license_src.exists():
            shutil.copyfile(license_src, LICENSE_OUT)
        else:
            print("Warning: Lucide LICENSE not found next to icons folder; copy it into wwwroot/icons/default manually.",
                  file=sys.stderr)

        write_thumbnail([bodies[lucide_for[key]] for key in thumbnail_keys], version)
        write_keys(categories)
        write_preview(categories, all_keys, symbols, version)

        print(f"{len(all_keys)} keys, {len(distinct)} distinct symbols, "
              f"sprite {SPRITE_OUT.stat().st_size / 1024:.1f} KB")

        problems = check_pack_map(all_keys, version)
        if problems:
            print(f"\n{PACK_FILE.relative_to(PROJECT_ROOT)} is out of date with icon-map.json:",
                  file=sys.stderr)
            print("\n".join(problems), file=sys.stderr)
            return 1
        return 0
    finally:
        if tmp:
            shutil.rmtree(tmp, ignore_errors=True)


def write_thumbnail(bodies: list[str], version: str) -> None:
    """A 3-column grid of sample icons on a card. Colours are fixed because the image is shown via <img>,
    where currentColor does not reach in from the page."""
    cols, cell, pad = 3, 40, 12
    rows = max(1, -(-len(bodies) // cols))
    width, height = cols * cell + pad * 2, rows * cell + pad * 2
    icons = []
    for i, body in enumerate(bodies):
        x = pad + (i % cols) * cell + (cell - 24) // 2
        y = pad + (i // cols) * cell + (cell - 24) // 2
        icons.append(f'<g transform="translate({x} {y})">{body}</g>')
    THUMBNAIL_OUT.write_text(
        f"<!-- OOS Default Pack thumbnail. Icons from Lucide v{version} (ISC). Generated by scripts/icons/build-icons.py -->\n"
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">'
        f'<rect width="{width}" height="{height}" rx="12" fill="#fafaf9" stroke="#e7e5e4"/>'
        '<g fill="none" stroke="#1c1917" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">'
        + "".join(icons) + "</g></svg>\n",
        encoding="utf-8")


def write_keys(categories: dict) -> None:
    out = GENERATED_HEADER + [
        f"namespace {ICONS_NS};",
        "",
        "/// <summary>",
        "/// The fixed set of semantic icon keys. Every icon provider is measured against this set;",
        "/// a complete reskin covers all of them. Plugin-specific icons use namespaced keys",
        "/// (<c>pluginid:name</c>) instead and are not part of this contract.",
        "/// </summary>",
        "public static partial class IconKeys",
        "{",
    ]
    for cat, info in categories.items():
        out += [
            f"    /// <summary>{html.escape(info['description'])}</summary>",
            f"    public static class {pascal(cat)}",
            "    {",
        ]
        for short in info["keys"]:
            out.append(f'        public const string {pascal(short)} = "{cat}.{short}";')
        out += ["    }", ""]

    out += [
        "    /// <summary>Every key in the contract, for coverage reports.</summary>",
        "    public static readonly IReadOnlyList<string> All =",
        "    [",
    ]
    for cat, info in categories.items():
        for short in info["keys"]:
            out.append(f"        {pascal(cat)}.{pascal(short)},")
    out += ["    ];", "}", ""]
    KEYS_OUT.parent.mkdir(parents=True, exist_ok=True)
    KEYS_OUT.write_text("\n".join(out), encoding="utf-8")


def check_pack_map(all_keys: list, version: str) -> list[str]:
    """The key map is maintained by hand in DefaultIconPack.cs (a pack is one file), so this only
    checks it against icon-map.json and reports the lines to change."""
    source = PACK_FILE.read_text(encoding="utf-8")
    found = dict(MAP_ENTRY.findall(source))
    expected = {f"{cat}.{short}": f"lucide-{lucide}" for cat, short, lucide in all_keys}
    problems = []

    version_match = MAP_VERSION.search(source)
    if not version_match or version_match.group(1) != f"lucide-{version}":
        problems.append(f'  set:    public const string Version = "lucide-{version}";')
    for key, symbol in expected.items():
        if key not in found:
            problems.append(f'  add:    ["{key}"] = "{symbol}",')
        elif found[key] != symbol:
            problems.append(f'  change: ["{key}"] = "{symbol}",   (currently "{found[key]}")')
    for key in found.keys() - expected.keys():
        problems.append(f'  remove: ["{key}"]   (not in icon-map.json)')
    return problems


def write_preview(categories: dict, all_keys: list, symbols: list, version: str) -> None:
    sections = []
    for cat, info in categories.items():
        tiles = "".join(
            f'<div class="tile"><svg class="i"><use href="#lucide-{lucide}"/></svg>'
            f'<code>{cat}.{short}</code><small>{lucide}</small></div>'
            for c, short, lucide in all_keys if c == cat
        )
        sections.append(
            f"<section><h2>{cat} <span>{len(info['keys'])}</span></h2>"
            f"<p>{html.escape(info['description'])}</p><div class=\"grid\">{tiles}</div></section>")

    page = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>OOS icon keys</title>
<style>
:root {{ --bg:#fafaf9; --fg:#1c1917; --muted:#78716c; --card:#fff; --line:#e7e5e4; color-scheme: light dark; }}
@media (prefers-color-scheme: dark) {{ :root {{ --bg:#1c1917; --fg:#f5f5f4; --muted:#a8a29e; --card:#292524; --line:#44403c; }} }}
body {{ margin:0; padding:1.5rem; background:var(--bg); color:var(--fg); font:15px/1.4 system-ui, sans-serif; }}
h1 {{ margin:0 0 .25rem; }} h2 span {{ color:var(--muted); font-weight:400; font-size:.8em; }}
p {{ color:var(--muted); margin:.25rem 0 1rem; }}
.grid {{ display:grid; grid-template-columns:repeat(auto-fill, minmax(9.5rem, 1fr)); gap:.5rem; }}
.tile {{ display:flex; flex-direction:column; align-items:center; gap:.35rem; padding:.85rem .5rem;
        background:var(--card); border:1px solid var(--line); border-radius:.5rem; text-align:center; }}
.tile code {{ font-size:.78rem; }} .tile small {{ color:var(--muted); font-size:.7rem; }}
.i {{ width:28px; height:28px; fill:none; stroke:currentColor; stroke-width:2; stroke-linecap:round; stroke-linejoin:round; }}
</style></head><body>
<svg xmlns="http://www.w3.org/2000/svg" style="display:none"><defs>{"".join(symbols)}</defs></svg>
<h1>OOS icon keys</h1>
<p>{len(all_keys)} keys, shown with the Default Pack: Lucide v{version} (ISC). Generated by scripts/icons/build-icons.py.</p>
{"".join(sections)}
</body></html>
"""
    PREVIEW_OUT.parent.mkdir(parents=True, exist_ok=True)
    PREVIEW_OUT.write_text(page, encoding="utf-8")


if __name__ == "__main__":
    sys.exit(main())
