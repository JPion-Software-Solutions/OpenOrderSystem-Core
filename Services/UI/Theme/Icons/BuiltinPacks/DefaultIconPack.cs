namespace OpenOrderSystem.Core.Services.UI.Theme.Icons.BuiltinPacks;

/// <summary>
/// The icon pack that ships with OOS, backed by a Lucide SVG sprite
/// (<c>wwwroot/icons/default/sprite.svg</c>). It covers every key in
/// <see cref="Icons.IconKeys"/>, so a key never resolves to nothing unless a
/// higher provider asks for that.
/// </summary>
/// <remarks>
/// The sprite, thumbnail and <see cref="Icons.IconKeys"/> are generated by
/// <c>scripts/icons/build-icons.py</c> from <c>scripts/icons/icon-map.json</c>.
/// <see cref="DefaultPackIconMap"/> lives in this file so the pack is self-contained, and is edited by hand;
/// the script checks it against <c>icon-map.json</c> and lists any lines to change.
/// Namespaced plugin keys (<c>pluginid:name</c>) are passed on, since plugins ship their own fallbacks.
/// </remarks>
public sealed class DefaultIconPack : IIconProvider
{
    /// <summary>The value of <see cref="Name"/>. Stored in the priority ladder, so it must not change.</summary>
    public const string ProviderName = "Default";

    /// <summary>Public URL of the sprite, versioned so a regenerated set busts browser caches.</summary>
    public const string SpriteUrl = "/icons/default/sprite.svg?v=" + DefaultPackIconMap.Version;

    private readonly IReadOnlyDictionary<string, string> _markup;

    public DefaultIconPack()
    {
        _markup = DefaultPackIconMap.Symbols.ToDictionary(
            pair => pair.Key,
            pair => BuildMarkup(pair.Value),
            StringComparer.Ordinal);
        IconKeys = [.. DefaultPackIconMap.Symbols.Keys];
    }

    /// <inheritdoc />
    public string Name => ProviderName;

    /// <inheritdoc />
    public string Description => "The standard OOS icon set, built from Lucide icons. Covers every icon key.";

    /// <inheritdoc />
    public string ThumbnailUrl => "/icons/default/thumbnail.svg?v=" + DefaultPackIconMap.Version;

    /// <inheritdoc />
    public string[] IconKeys { get; }

    /// <inheritdoc />
    public HtmlString? ResolveIcon(string key) =>
        _markup.TryGetValue(key, out var markup) ? new HtmlString(markup) : null;

    /// <summary>
    /// Stroke styling sits on the outer element so it inherits into the sprite symbol;
    /// colour comes from <c>currentColor</c>, so icons follow the surrounding text and theme.
    /// Size is set in CSS (<c>.oos-icon</c> in <c>oos-icons.css</c>).
    /// </summary>
    private static string BuildMarkup(string symbolId) =>
        $"<svg class=\"oos-icon\" viewBox=\"0 0 24 24\" fill=\"none\" stroke=\"currentColor\" " +
        $"stroke-width=\"2\" stroke-linecap=\"round\" stroke-linejoin=\"round\" " +
        $"aria-hidden=\"true\" focusable=\"false\"><use href=\"{SpriteUrl}#{symbolId}\"></use></svg>";
}
